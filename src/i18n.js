let currentLang = localStorage.getItem('mason_lang') || 'ru';

export function initLang() {
  const saved = localStorage.getItem('mason_lang');
  if (saved) currentLang = saved;
}

export function getLang() { return currentLang; }
export function setLang(l) { currentLang = l; localStorage.setItem('mason_lang', l); }

export function t(key) {
  return (STRINGS[currentLang] && STRINGS[currentLang][key]) || (STRINGS.en[key]) || key;
}
